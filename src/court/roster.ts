export const SPECIALISTS: readonly SeatDef[] = POOL.map(([id, title, emoji, arena, domain, tags, brief]) => ({
  id,
  title,
  emoji,
  arena,
  domain,
  tags: tags.split(",").map((t) => t.trim().toLowerCase()),
  brief,
  kind: "specialist",
}));

export const SEAT_BY_ID: ReadonlyMap<string, SeatDef> = new Map(
  [...CORE_SEATS, ...SPECIALISTS].map((s) => [s.id, s]),
);

export interface CaseText {
  arena: "CRYPTO" | "EQUITIES";
  symbol: string;
  /** catalyst headline + summary, research findings, facts: everything the News & Research desk produced */
  text: string;
}

/** Keyword relevance of one specialist to a case. Pure. */
export function relevance(s: SeatDef, c: CaseText): number {
  if (s.arena !== "ANY" && s.arena !== c.arena) return 0;
  const t = ` ${c.text.toLowerCase().replace(/[^a-z0-9&/.+ -]/g, " ")} `;
  let score = 0;
  for (const tag of s.tags) {
    const re = new RegExp(`[^a-z0-9]${tag.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`, "i");
    if (re.test(t)) score += tag.includes(" ") ? 2 : 1;
  }
  return score;
}

/** The specialists worth asking Clef about: matching ones first (by score, then pool order), at most `n`. Pure. */
export function shortlist(c: CaseText, n: number): SeatDef[] {
  return SPECIALISTS.map((s, i) => ({ s, i, r: relevance(s, c) }))
    .filter((x) => x.r > 0)
    .sort((a, b) => b.r - a.r || a.i - b.i)
    .slice(0, n)
    .map((x) => x.s);
}

/** Courtroom phrasing for a seat that has nothing more to add (raw NO_OBJECTION never reaches a person). Pure. */
export const REST_PHRASES = [
  "Resting my case.",
  "No further objections, Your Honor.",
  "Nothing further from this seat.",
  "The record speaks for itself; I rest.",
  "No further questions.",
  "I yield the floor.",
] as const;
export function restPhrase(seatId: string, round: number): string {
  let h = round * 31;
  for (const c of seatId) h = (h * 33 + c.charCodeAt(0)) >>> 0;
  return REST_PHRASES[h % REST_PHRASES.length] as string;
}
