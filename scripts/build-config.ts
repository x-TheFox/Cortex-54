// Validates config/ against the zod contracts and emits src/generated/config.ts for the Worker bundle.
// Runs on Node (type stripping): `node scripts/build-config.ts`. Fails the build on any violation,
// which is how "doctrine may only be tighter than the constitution" is enforced before deploy.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { CalibrationSchema } from "../src/contracts/calibration.ts";
import { ConstitutionSchema } from "../src/contracts/constitution.ts";
import { DoctrineSchema, doctrineViolations } from "../src/contracts/doctrine.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p: string) => readFileSync(join(root, p), "utf8");
const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");

const constitutionRaw = read("config/constitution.json");
const doctrineRaw = read("config/doctrine.yaml");
const scarRaw = read("config/scar-tissue.yaml");
const calibrationRaw = read("config/calibration.json");

const constitution = ConstitutionSchema.parse(JSON.parse(constitutionRaw));
const doctrine = DoctrineSchema.parse(parse(doctrineRaw));
const scarTissue = parse(scarRaw) as unknown;
const calibration = CalibrationSchema.parse(JSON.parse(calibrationRaw));

const violations = doctrineViolations(doctrine, constitution);
if (violations.length > 0) {
  console.error(`Doctrine violates the constitution:\n - ${violations.join("\n - ")}`);
  process.exit(1);
}

const out = `// GENERATED by scripts/build-config.ts — do not edit. Source of truth: config/.
import type { Constitution } from "../contracts/constitution.ts";
import type { Doctrine } from "../contracts/doctrine.ts";
import type { Calibration } from "../contracts/calibration.ts";
export const CONSTITUTION_SHA256 = ${JSON.stringify(sha256(constitutionRaw))};
export const DOCTRINE_SHA256 = ${JSON.stringify(sha256(doctrineRaw))};
export const CONSTITUTION: Constitution = ${JSON.stringify(constitution)};
export const DOCTRINE: Doctrine = ${JSON.stringify(doctrine)};
export const SCAR_TISSUE: unknown = ${JSON.stringify(scarTissue)};
export const CALIBRATION: Calibration = ${JSON.stringify(calibration)};
`;

const target = join(root, "src/generated/config.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`config ok → src/generated/config.ts (constitution ${sha256(constitutionRaw).slice(0, 12)})`);
